import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

import { normalizePath } from "vite";
import type { Plugin } from "vite";

import { buildPlugin, serverBuildOf } from "./build.ts";
import { ServerEnvironment } from "./environment.ts";
import { previewPlugin } from "./preview.ts";
import { ENVIRONMENT } from "./types.ts";
import type { CyrenexOptions, ResolvedOptions, Runtime } from "./types.ts";

export type { BuildOptions, CyrenexOptions, RestartEvent, Runtime } from "./types.ts";

const asArray = (value: string | string[] | undefined) =>
  value === undefined ? [] : Array.isArray(value) ? value : [value];

function resolveOptions(options: CyrenexOptions): ResolvedOptions {
  const runtime = options.runtime ?? (process.env.CYRENEX_RUNTIME as Runtime | undefined) ?? "bun";
  if (runtime !== "bun" && runtime !== "node") {
    throw new TypeError(`cyrenex: unknown runtime "${String(runtime)}", expected "bun" or "node"`);
  }
  const build = options.build;
  const input = build ? build.client : undefined;
  const client = typeof input === "string" ? { outDir: input } : input;
  return {
    server: options.server ?? "server/main.ts",
    app: options.app ?? "server/app.ts",
    runtime,
    routes: options.routes ?? ["/api", "/ws"],
    watch: options.watch ?? [],
    dts: options.dts ?? "cyrenex-env.d.ts",
    execArgv: [...inspectArgv(options.inspect), ...(options.execArgv ?? [])],
    env: options.env ?? {},
    shutdownTimeout: options.shutdownTimeout ?? 1000,
    build:
      build === false
        ? false
        : {
            server:
              build?.server === false
                ? false
                : {
                    outDir: build?.server?.outDir ?? "dist/server",
                    auto: options.server === undefined && build?.server === undefined,
                  },
            client: { outDir: client?.outDir, copyTo: asArray(client?.copyTo) },
            start: build?.start,
          },
  };
}

function inspectArgv(inspect: CyrenexOptions["inspect"]): string[] {
  if (inspect === undefined || inspect === false) return [];
  if (inspect === true) return ["--inspect=127.0.0.1:9229"];
  return [`--inspect=${typeof inspect === "number" ? `127.0.0.1:${inspect}` : inspect}`];
}

export function renderDts(dtsFile: string, entryFile: string): string {
  let specifier = normalizePath(relative(dirname(dtsFile), entryFile));
  if (!specifier.startsWith(".")) specifier = `./${specifier}`;
  return `// Generated by cyrenex/vite. Do not edit.
declare module "cyrenex/client" {
  interface Register {
    app: typeof import("${specifier}").default;
  }
}

declare module "vite/types/customEvent.d.ts" {
  interface CustomEventMap {
    /** The app process restarted after a server change. */
    "cyrenex:restart": { runtime: "bun" | "node" };
  }
}

export {};
`;
}

/** Write the `cyrenex/client` augmentation; runs for both `dev` and `build`. */
function dtsPlugin(options: ResolvedOptions): Plugin {
  return {
    name: "cyrenex:dts",
    configResolved(config) {
      if (options.dts === false) return;
      const file = resolve(config.root, options.dts);
      const content = renderDts(file, resolve(config.root, options.app));
      if (existsSync(file) && readFileSync(file, "utf8") === content) return;
      writeFileSync(file, content);
    },
  };
}

/** The server environment, shared by the dev server and the server build. */
function environmentPlugin(options: ResolvedOptions): Plugin {
  return {
    name: "cyrenex:environment",
    config(user, { command }) {
      if (command === "build" && !serverBuildOf(options, resolve(user.root ?? process.cwd()))) {
        return;
      }
      return {
        environments: {
          [ENVIRONMENT]: {
            consumer: "server",
            resolve: {
              // Match package exports to the app's runtime rather than the Vite host.
              conditions:
                options.runtime === "node"
                  ? ["node", "development|production"]
                  : ["bun", "node", "development|production"],
            },
          },
        },
      };
    },
  };
}

/** Run the server entry in a child process and forward matching requests to it. */
function devPlugin(options: ResolvedOptions): Plugin {
  return {
    name: "cyrenex:dev",
    apply: "serve",

    config() {
      return {
        environments: {
          [ENVIRONMENT]: {
            dev: {
              createEnvironment: (name, config) => new ServerEnvironment(name, config, options),
            },
          },
        },
      };
    },

    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const environment = server.environments[ENVIRONMENT] as ServerEnvironment;
        if (!environment.matches(req.url ?? "/")) return next();
        void environment.handle(req, res).catch(next);
      });
    },

    hotUpdate() {
      // Server changes replace the process; module HMR must not re-evaluate the app.
      if (this.environment.name === ENVIRONMENT) return [];
    },
  };
}

/**
 * Develop and build a server app (`server/main.ts`, started with `start(app)`) inside Vite.
 *
 * ```ts
 * export default defineConfig({ plugins: [cyrenex()] });
 * ```
 */
export default function cyrenex(options: CyrenexOptions = {}): Plugin[] {
  const resolved = resolveOptions(options);
  return [
    dtsPlugin(resolved),
    environmentPlugin(resolved),
    devPlugin(resolved),
    buildPlugin(resolved),
    previewPlugin(resolved),
  ];
}
